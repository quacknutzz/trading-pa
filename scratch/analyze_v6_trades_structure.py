"""
scratch/analyze_v6_trades_structure.py
Analyze all trades generated by V6++ on the 61-day cached dataset.
Inspect entry prices, MFE, MAE, and where the peak of the trade occurred relative to:
1. Daily Floor Pivots (R1, R2, S1, S2)
2. Camarilla Pivots (H3, H4, L3, L4)
3. Previous Day High / Low (PDH, PDL)
4. Session VWAP + 2.0 Sigma Bands
5. 5-minute Swing Lows / Highs (structural trailing stops)
"""
import sys, os, pickle, math
from datetime import datetime
import numpy as np
import pandas as pd

sys.stdout.reconfigure(encoding='utf-8')
sys.path.insert(0, 'sim')
import datafeed
from simulator import Simulator

u = datafeed.load_universe()
with open('sim/cache/nse_5m_60d.pkl', 'rb') as f:
    payload = pickle.load(f)
raw = payload['raw']
idx = payload['idx']

sym0 = list(raw.keys())[0]
dates = sorted(list(set(raw[sym0].index.date)))

master = Simulator('replay', datetime.combine(dates[0], datetime.min.time()), starting_capital=500000.0)
master.load(raw, u, idx)

# Run baseline v6_profit_max
all_trades = []
for d in dates:
    dt = datetime.combine(d, datetime.min.time())
    sim = Simulator('replay', dt, strategy='v6_profit_max', starting_capital=500000.0)
    sim.syms = master.syms
    sim.indices = master.indices
    sim.nifty_pos = master.nifty_pos
    sim.nifty_e10 = master.nifty_e10
    sim.nifty_e21 = master.nifty_e21
    sim.nifty_e30 = master.nifty_e30
    for t in sim.session_bar_times():
        sim.step(t)
    for c in sim.closed:
        all_trades.append(c)

print(f"Total trades executed by baseline: {len(all_trades)}")

# Now for each trade, let's analyze the exact market structure on that day
trade_details = []
mfe_exceeded_cap = 0
mfe_list = []
runner_mfe_list = [] # trades where MFE >= 0.95%

# Detailed metrics
hit_r1_before_peak = 0
hit_r2_before_peak = 0
hit_pdh_before_peak = 0
hit_h3_before_peak = 0
hit_h4_before_peak = 0
hit_vwap2s_before_peak = 0

# For trailing stop loss analysis
swing_sl_stats = []

for tr in all_trades:
    sym = tr['symbol']
    side = tr['side']
    entry = tr['entry']
    exit_px = tr['exit']
    entry_time = pd.Timestamp(tr['entry_time'])
    exit_time = pd.Timestamp(tr['exit_time'])
    d = entry_time.date()
    
    sd = master.syms[sym]
    df = sd.df
    
    # Get previous day OHLC
    prev_dates = [dt for dt in dates if dt < d]
    if not prev_dates:
        continue
    prev_d = prev_dates[-1]
    prev_df = df.loc[df.index.date == prev_d]
    if len(prev_df) == 0:
        continue
    
    pdh = float(prev_df['high'].max())
    pdl = float(prev_df['low'].min())
    pdc = float(prev_df['close'].iloc[-1])
    rng = pdh - pdl
    
    P = (pdh + pdl + pdc) / 3.0
    R1 = 2.0 * P - pdl
    S1 = 2.0 * P - pdh
    R2 = P + rng
    S2 = P - rng
    
    H4 = pdc + 0.55 * rng
    H3 = pdc + 0.275 * rng
    L3 = pdc - 0.275 * rng
    L4 = pdc - 0.55 * rng
    
    # Opening range (09:15 to 09:30)
    day_df = df.loc[df.index.date == d]
    orb_df = day_df.between_time('09:15', '09:25')
    orh = float(orb_df['high'].max()) if len(orb_df) else pdh
    orl = float(orb_df['low'].min()) if len(orb_df) else pdl
    
    # Find trade bars
    t_bars = day_df.loc[(day_df.index >= entry_time) & (day_df.index <= exit_time)]
    day_after_entry = day_df.loc[day_df.index >= entry_time]
    
    # Intraday VWAP & 2 Sigma at entry and peak
    h_arr = day_df['high'].values.astype(np.float64)
    l_arr = day_df['low'].values.astype(np.float64)
    c_arr = day_df['close'].values.astype(np.float64)
    v_arr = day_df['volume'].values.astype(np.float64)
    tp = (h_arr + l_arr + c_arr) / 3.0
    cum_v = np.cumsum(v_arr)
    cum_pv = np.cumsum(tp * v_arr)
    cum_pv2 = np.cumsum(tp * tp * v_arr)
    valid_v = cum_v > 0
    vwap = np.zeros_like(tp)
    vwap[valid_v] = cum_pv[valid_v] / cum_v[valid_v]
    var = np.maximum(0.0, (cum_pv2[valid_v] / cum_v[valid_v]) - (vwap[valid_v] ** 2))
    std = np.sqrt(var)
    upper_2s = np.zeros_like(tp)
    lower_2s = np.zeros_like(tp)
    upper_2s[valid_v] = vwap[valid_v] + 2.0 * std
    lower_2s[valid_v] = vwap[valid_v] - 2.0 * std
    
    # MFE of trade during session after entry
    sgn = 1 if side == 'BUY' else -1
    max_favorable = -999.0
    peak_px = entry
    peak_idx = -1
    
    for idx_b, ts in enumerate(day_after_entry.index):
        b_hi = float(day_after_entry.loc[ts, 'high'])
        b_lo = float(day_after_entry.loc[ts, 'low'])
        fav = (b_hi / entry - 1.0) * 100.0 if sgn > 0 else (1.0 - b_lo / entry) * 100.0
        if fav > max_favorable:
            max_favorable = fav
            peak_px = b_hi if sgn > 0 else b_lo
            peak_ts = ts
    
    mfe_list.append(max_favorable)
    if max_favorable >= 0.95:
        mfe_exceeded_cap += 1
        runner_mfe_list.append(max_favorable)
        
    # Check if peak reached R1, R2, PDH, H3, H4, VWAP+2S
    pos_idx = day_df.index.get_loc(peak_ts) if peak_ts in day_df.index else -1
    v2s_at_peak = upper_2s[pos_idx] if (pos_idx >= 0 and sgn > 0) else lower_2s[pos_idx]
    
    tagged_r1 = (peak_px >= R1) if sgn > 0 else (peak_px <= S1)
    tagged_r2 = (peak_px >= R2) if sgn > 0 else (peak_px <= S2)
    tagged_pdh = (peak_px >= pdh) if sgn > 0 else (peak_px <= pdl)
    tagged_h3 = (peak_px >= H3) if sgn > 0 else (peak_px <= L3)
    tagged_h4 = (peak_px >= H4) if sgn > 0 else (peak_px <= L4)
    tagged_v2s = (peak_px >= v2s_at_peak) if sgn > 0 else (peak_px <= v2s_at_peak)
    
    trade_details.append({
        'symbol': sym, 'side': side, 'entry': entry, 'exit': exit_px,
        'gross': tr['gross'], 'net': tr['net'], 'reason': tr['reason'],
        'actual_mfe': tr['mfe'], 'full_day_mfe': round(max_favorable, 2),
        'R1': round(R1 if sgn > 0 else S1, 2),
        'R2': round(R2 if sgn > 0 else S2, 2),
        'PDH': round(pdh if sgn > 0 else pdl, 2),
        'H3': round(H3 if sgn > 0 else L3, 2),
        'H4': round(H4 if sgn > 0 else L4, 2),
        'V2S': round(v2s_at_peak, 2),
        'tagged_R1': tagged_r1, 'tagged_R2': tagged_r2,
        'tagged_PDH': tagged_pdh, 'tagged_H3': tagged_h3,
        'tagged_H4': tagged_h4, 'tagged_V2S': tagged_v2s
    })

df_tr = pd.DataFrame(trade_details)
print("\n==========================================================================")
print("EXCURSION & RESISTANCE REACH ANALYSIS ON ACTUAL BASELINE TRADES (N=50)")
print("==========================================================================")
print(f"Trades with Full-Day MFE >= 0.95% (Capped by Fixed Target): {mfe_exceeded_cap} / 50 ({mfe_exceeded_cap/50*100:.1f}%)")
print(f"Average Full-Day MFE of ALL trades: {np.mean(mfe_list):.2f}% (Median: {np.median(mfe_list):.2f}%)")
print(f"Average Full-Day MFE of Runners (MFE >= 0.95%): {np.mean(runner_mfe_list):.2f}% (Median: {np.median(runner_mfe_list):.2f}%, Max: {np.max(runner_mfe_list):.2f}%)")

print("\n--- Structural Levels Reached by Trades ---")
print(f"Reached R1 / S1:               {df_tr['tagged_R1'].sum()} / 50 ({df_tr['tagged_R1'].mean()*100:.1f}%)")
print(f"Reached Camarilla H3 / L3:     {df_tr['tagged_H3'].sum()} / 50 ({df_tr['tagged_H3'].mean()*100:.1f}%)")
print(f"Reached Previous Day High/Low: {df_tr['tagged_PDH'].sum()} / 50 ({df_tr['tagged_PDH'].mean()*100:.1f}%)")
print(f"Reached VWAP +/- 2.0 Sigma:    {df_tr['tagged_V2S'].sum()} / 50 ({df_tr['tagged_V2S'].mean()*100:.1f}%)")
print(f"Reached Camarilla H4 / L4:     {df_tr['tagged_H4'].sum()} / 50 ({df_tr['tagged_H4'].mean()*100:.1f}%)")
print(f"Reached R2 / S2:               {df_tr['tagged_R2'].sum()} / 50 ({df_tr['tagged_R2'].mean()*100:.1f}%)")

print("\n--- Top 15 Runners: What was Left on the Table vs Where They Peaked ---")
runners = df_tr.sort_values(by='full_day_mfe', ascending=False).head(15)
for idx, r in runners.iterrows():
    levels_hit = []
    if r['tagged_R1']: levels_hit.append('R1')
    if r['tagged_H3']: levels_hit.append('H3')
    if r['tagged_PDH']: levels_hit.append('PDH')
    if r['tagged_V2S']: levels_hit.append('VWAP+2S')
    if r['tagged_H4']: levels_hit.append('H4')
    if r['tagged_R2']: levels_hit.append('R2')
    hit_str = ', '.join(levels_hit) if levels_hit else 'None'
    print(f"{r['symbol']} ({r['side']}): Realized Net: Rs. {r['net']:+7.1f} | Fixed MFE: {r['actual_mfe']:.2f}% | Full MFE: {r['full_day_mfe']:.2f}% | Hit: {hit_str} | Exit: {r['reason'][:22]}")
